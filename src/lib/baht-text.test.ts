import { describe, expect, it } from 'vitest';
import { bahtText } from './baht-text';

describe('bahtText', () => {
	it.each([
		[0, 'ศูนย์บาทถ้วน'],
		[1, 'หนึ่งบาทถ้วน'],
		[11, 'สิบเอ็ดบาทถ้วน'],
		[21, 'ยี่สิบเอ็ดบาทถ้วน'],
		[100, 'หนึ่งร้อยบาทถ้วน'],
		[1234.5, 'หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์'],
		[0.25, 'ศูนย์บาทยี่สิบห้าสตางค์'],
		[0.01, 'ศูนย์บาทหนึ่งสตางค์'],
		[1000000, 'หนึ่งล้านบาทถ้วน'],
		[1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
		[184500, 'หนึ่งแสนแปดหมื่นสี่พันห้าร้อยบาทถ้วน'],
		[2860450, 'สองล้านแปดแสนหกหมื่นสี่ร้อยห้าสิบบาทถ้วน']
	])('%s', (n, expected) => {
		expect(bahtText(n)).toBe(expected);
	});
});
